def codeAgent(state: AgentState):
    """It is a python code agent for a sales AI assistant, Which generates the code for given prompt using python tool
    and then evaluate the code and get the response"""

    dataframeprompt = promptCreationForDataFrame()

    prompt1 = """
    You are a **brilliant Python data analysis expert**.

    Your job is to write a clean and executable Python code snippet based on the user's request.
    
    Assume the following:
    - A pandas DataFrame named `df` is already loaded and available.
    - Do not explain anything — return only the code.
    - Focus on using pandas and matplotlib/seaborn as needed.
    """

    prompt2 = """
    User request:
    {user_prompt}
    
    Important Instructions:
    -Return only code in python language with correct syntax and correct indentation , the entire code should be in "python cell"
    -Donot give any other prefix "python" or other , suffix to the code in the response except the code.Do not write unnecessary
    suggestions in the code and explanations.
    -Donot write any print statements and log statements
    -Write the code in single python script (not in multiple chunks)
    -Store the final answer to the "result" variable.
    """

    prompt_template = prompt1 + "/n" + dataframeprompt + "/n" + prompt2

    global routerPrompt
    codePrompt = PromptTemplate(
        template=prompt_template,
        input_variables=["user_prompt"],
    )
    global query_decomposer
    query_decomposer = codePrompt | llm

    user_query = state["user_input"]
    flow = getGraph()
    decision = flow.invoke(state)
    if "steps" in state:
        steps = state["steps"]
    else:
        steps = []
    steps.append("CodeAgent")
    decision = decision["generation"]
    return {
        "user_input": user_query,
        "generation": decision,
        "steps": steps
    }
