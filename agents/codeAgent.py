def codeExtraction(state: AgentState):
    """It is a python code agent for a sales AI assistant, which extracts the code snippet from the generated response from code Generator agent"""
    user_query = state["user_input"]
    codeText = state["generation"]
    # Extract code between triple backticks or similar pattern
    code_blocks = re.findall(r"```(?:python)?\n(.*?)```", codeText, re.DOTALL)
    if code_blocks:
        # Join multiple code blocks if needed
        code_only = "\n".join(code_blocks).strip()
    else:
        code_only = codeText

    print(code_only)
    if "steps" in state:
        steps = state["steps"]
    else:
        steps = []
    steps.append("CodeAgent-CodeExtractor")
    decision = code_only
    return {
        "user_input": user_query,
        "generation": decision,
        "steps": steps
    }

